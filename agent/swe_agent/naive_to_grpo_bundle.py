"""Convert naive M-rollout InstanceRecord -> GRPOExportBundle.

One ExportGroup per instance, with M=8 ExportSamples (one per linear
rollout). The whole chat (system + user + all assistant tool turns) is the
training sequence; only assistant tokens are loss-masked. There is no
"parent prefix" to strip — each rollout was a fresh session, so the
sys+user prompt at the head is the same shared prefix across all M
siblings in the group (encoded implicitly via the same loss-mask scheme).

The token-level prefix invariant + per-turn loss-mask placement is COPIED
verbatim from lane_to_grpo_bundle._build_branch_sample. The only logical
difference is that we don't pull "parent_messages" from a MidCp snapshot
— there is no MidCp. We split at the first assistant message; sys+user
messages stay in the prompt field but are not loss-trainable (mask=0 on
those positions).
"""

from __future__ import annotations

import math as _math

from swe_agent.contracts import ExportGroup, ExportSample, GRPOExportBundle, has_exact_rollout_tokens
from swe_agent.naive_search import NaiveRecord, NaiveRollout


def _build_rollout_sample(
    *,
    instance_id: str,
    rollout: NaiveRollout,
    assistant_step_limit: int | None = None,
) -> ExportSample | None:
    """Build one ExportSample from a single naive rollout.

    Token path: same logic as lane_to_grpo_bundle._build_branch_sample.
    rollout.messages contains the FULL chat (sys+user+asst+tool). We
    assemble (last_asst.prompt_token_ids + last_asst.token_ids) as the
    full sequence and set mask=1 only on each assistant turn's tokens.
    """
    if rollout.error is not None or (
        rollout.training_reward is None and rollout.gt_score is None
    ):
        return None
    reward = float(
        rollout.training_reward
        if rollout.training_reward is not None
        else rollout.gt_score
    )
    if not _math.isfinite(reward):
        return None

    full_messages = list(rollout.messages or [])
    if not full_messages:
        return None

    token_ids: list[int] | None = None
    loss_mask: list[int] | None = None
    response_length: int | None = None
    rollout_logprobs: list[float] | None = None

    assistant_messages = [m for m in full_messages if m.get("role") == "assistant"]
    asst_with_tokens = (
        assistant_messages[:assistant_step_limit]
        if assistant_step_limit is not None
        else assistant_messages
    )
    if not asst_with_tokens or not all(
        map(has_exact_rollout_tokens, asst_with_tokens)
    ):
        return None
    if asst_with_tokens:
        last = asst_with_tokens[-1]
        last_prompt = list(last["prompt_token_ids"])
        last_out = list(last["token_ids"])
        full_token_ids = last_prompt + last_out
        # The "parent prefix" for a fresh-session rollout is just the
        # system+user tokens that exist before the FIRST assistant turn.
        # Use the first assistant's prompt_token_ids as that boundary —
        # everything before it is sys+user (untrainable), everything from
        # there forward is generated by the policy and gets loss-masked.
        parent_prefix_len = len(asst_with_tokens[0]["prompt_token_ids"])
        response_length = max(0, len(full_token_ids) - parent_prefix_len)
        if response_length == 0:
            return None
        mask = [0] * len(full_token_ids)
        # Dense per-response-token logprob vector, aligned with
        # loss_mask[-response_length:]. Non-assistant positions stay 0.0;
        # TIS clamps the resulting ratio so the masked loss contribution
        # there is zero anyway, but the vector LENGTH must match the
        # loss_mask slice so torch.cat downstream succeeds.
        dense_lp: list[float] = [0.0] * response_length
        for asst in asst_with_tokens:
            a_prompt = list(asst["prompt_token_ids"])
            # HARD ASSERT — same as lanes / pds: a_i.prompt must be a true
            # prefix of last.prompt. The custom chat template guarantees
            # this; if it ever breaks, PG ratio explodes.
            if len(a_prompt) > len(last_prompt):
                raise AssertionError(
                    f"naive sample {rollout.node_id}: a_i.prompt len "
                    f"({len(a_prompt)}) exceeds last.prompt len "
                    f"({len(last_prompt)}) — invariant violated."
                )
            if last_prompt[: len(a_prompt)] != a_prompt:
                div = next(
                    (i for i in range(len(a_prompt))
                     if last_prompt[i] != a_prompt[i]),
                    -1,
                )
                raise AssertionError(
                    f"naive sample {rollout.node_id}: a_i.prompt is NOT a "
                    f"prefix of last.prompt. first_divergence_idx={div}, "
                    f"len(a_i)={len(a_prompt)}, len(last)={len(last_prompt)}. "
                    f"Custom chat template must be broken — fix tokenization.py."
                )
            start = len(a_prompt)
            out_tok = asst["token_ids"]
            end = min(start + len(out_tok), len(mask))
            for k in range(start, end):
                mask[k] = 1
            lp = asst["logprobs"]
            for j in range(end - start):
                local_pos = (start - parent_prefix_len) + j
                if 0 <= local_pos < response_length:
                    dense_lp[local_pos] = float(lp[j])
        token_ids = full_token_ids
        loss_mask = mask
        rollout_logprobs = dense_lp

    # Split prompt (sys+user) from turns (everything assistant onward) for
    # build_training_messages downstream.  With a cap, physically discard all
    # messages after the final retained assistant turn; terminal continuation
    # exists only for evaluator diagnostics and must not enter actor forward.
    first_asst_idx = next(
        (i for i, m in enumerate(full_messages) if m.get("role") == "assistant"),
        len(full_messages),
    )
    cutoff_idx = len(full_messages)
    if assistant_step_limit is not None:
        assistant_count = 0
        for message_index, message in enumerate(full_messages):
            if message.get("role") != "assistant":
                continue
            assistant_count += 1
            if assistant_count >= assistant_step_limit:
                cutoff_idx = message_index + 1
                break
    prompt_messages = [
        {"role": m.get("role", "user"), "content": m.get("content", "") or ""}
        for m in full_messages[:first_asst_idx]
    ]
    turn_messages = [
        {"role": m.get("role", "assistant"), "content": m.get("content", "") or ""}
        for m in full_messages[first_asst_idx:cutoff_idx]
    ]

    full_step_count = len(rollout.step_cards)
    trained_step_count = (
        min(full_step_count, assistant_step_limit)
        if assistant_step_limit is not None
        else full_step_count
    )

    return ExportSample(
        sample_id=rollout.node_id,
        group_id=f"naive-{instance_id}",
        prompt=prompt_messages,
        turns=turn_messages,
        reward=float(reward),
        metadata={
            "rollout_index": rollout.rollout_index,
            "group_index": 0,
            "terminated_early": rollout.terminated_early,
            "raw_gt_score": rollout.gt_score,
            "raw_rubric_score": rollout.judge_score,
            "signed_mapped_judge_score": rollout.signed_judge_score,
            "reward_source": rollout.reward_source,
            "collapse_reward_applied": (
                rollout.reward_source == "code_mode_collapse"
            ),
            "collapse_reason": rollout.collapse_reason,
            "total_tokens": rollout.total_tokens,
            "parent_token_count": (len(token_ids) - response_length)
            if token_ids is not None and response_length is not None else None,
            "token_source": "sglang_stored",
            # Per-sample step counts — same keys as lanes for shared metric
            # aggregation in the rollout-fn (sample_cont_steps_mean etc.).
            "n_continuation_steps": trained_step_count,
            "n_parent_steps": 0,
            "n_full_trace_steps": full_step_count,
            "train_assistant_step_limit": assistant_step_limit,
            "n_discarded_steps": full_step_count - trained_step_count,
            # Patch field used by rollout metrics.
            "terminal_patch_len": len(rollout.terminal_patch or ""),
        },
        token_ids=token_ids,
        loss_mask=loss_mask,
        response_length=response_length,
        rollout_logprobs=rollout_logprobs,
    )


def naive_record_to_bundle(record: NaiveRecord) -> GRPOExportBundle:
    """Convert one NaiveRecord into a GRPOExportBundle.

    policy_groups: a single ExportGroup with M ExportSamples (one per
    naive rollout). If any rollout is invalid, the whole GRPO group is
    omitted because its sibling baseline is no longer trustworthy.

    rubric_groups: always empty (naive baseline has no rubric/judge).
    """
    samples: list[ExportSample] = []
    invalid_rollouts: list[str] = []
    raw_step_limit = record.config.get("train_assistant_step_limit")
    assistant_step_limit = (
        int(raw_step_limit) if raw_step_limit is not None else None
    )
    for r in record.rollouts:
        s = _build_rollout_sample(
            instance_id=record.instance_id,
            rollout=r,
            assistant_step_limit=assistant_step_limit,
        )
        if s is None:
            invalid_rollouts.append(r.node_id)
            continue
        samples.append(s)

    direct_judge = record.direct_judge or {}
    for sample in samples:
        sample.metadata = {
            **(sample.metadata or {}),
            "predicted_zero_variance": bool(
                direct_judge.get("predicted_zero_variance", False)
            ),
            "explicit_abstain": (
                (direct_judge.get("explicit_abstain") or {})
                .get("parsed", {})
                .get("should_abstain")
            ),
            "numeric_detector": direct_judge.get("numeric_detector"),
        }

    group_dropped_reason = (
        f"invalid_rollouts ({len(invalid_rollouts)}/{len(record.rollouts)})"
        if invalid_rollouts or not samples
        else None
    )

    policy_groups: list[ExportGroup] = []
    if group_dropped_reason is None:
        policy_groups.append(
            ExportGroup(
                group_id=samples[0].group_id,
                samples=samples,
                metadata={
                    "group_index": 0,
                    "n_rollouts": len(record.rollouts),
                    "n_real": len(samples),
                    "predicted_zero_variance": bool(
                        direct_judge.get("predicted_zero_variance", False)
                    ),
                },
            )
        )

    return GRPOExportBundle(
        instance_id=record.instance_id,
        run_dir=record.run_dir,
        policy_groups=policy_groups,
        rubric_groups=[],
        metadata={
            "config": record.config,
            "completed": record.completed,
            "error": record.error,
            "seconds": record.seconds,
            "num_rollouts": len(record.rollouts),
            "scheme": "naive_v1",
            "n_real": len(samples),
            "invalid_rollouts": invalid_rollouts,
            "group_dropped_reason": group_dropped_reason,
        },
    )
